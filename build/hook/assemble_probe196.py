# V06 D1: the chain continues (T2B, then the 0xD3 call in T3) ONLY after 0x12, 0x13, 0x14 (TYPE 3 and STATE 0/1/2). Ids
# 0x15 (STATE low word outside 0..2), 0x16 (TYPE is not 3) and 0x1E (a GetInfo call FALSE) are all >= 0x15: unsigned
# `cmp AL,#0x15 ; bcc` (bcc = AL >= 0x15, the probe139 polarity) ends the chain through FIN0 (slot 3 := 0, no arm).
# (The review's `cmp #0x16` would have let 0x15 through; 0x15 is also a "not a normal partition" answer.)
W(*CMPI_AL(ID_ST_OTHER)); BR(BCC, "FIN0")
BR(BRA, "FIN")
LBL("DO2B")
W(*LDI_AL(STAGE3)); W(ST_AL_Y(3))
BSR("T2B")
W(ST_AL_Y(5))
BR(BRA, "FIN")
LBL("DO3")
BSR("T3")
W(ST_AL_Y(5))
LBL("FIN0")
W(0x0014); W(ST_AL_Y(3))       # next = 0: the chain ends here
LBL("FIN")                      # speak slot 5, then arm slot 3 (if any) STAGE_MS later
W(LD_AL_Y(5))
BSR(SPEAK)                      # probe99's direct idiom, hardware-proven; no transform of ours exists in this image
W(LD_AL_Y(3)); W(CMP0); BR(BEQ, "FEND")
W(*LDI_AL(STAGE_MS)); W(ST_AL_Y(4))
BR(BRA, "SENDLATER")
LBL("FEND")
W(0xF80F)                       # leavel -8

# ---------------------------------------------------------------------- ARM (the press)
# MessageCancelFirst(task, id) for each stage id: TRUE = that stage's tick was pending, i.e. a census is running:
# this press is a STOP, nothing else is touched (silent). Else arm T1. (probe195's STOP, once per stage id.)
LBL("ARM")
W(0xF80B)                       # enterl -8
W(*LDI_AL(STAGE1)); W(ST_AL_Y(2))        # slot 2 = the id being tried: STAGE1 .. STAGE3 (0x12..0x15, consecutive)
