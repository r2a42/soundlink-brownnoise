W(0x0127)                       # (AL still 0) delay high = 0   slot1
W(LD_AL_Y(4))                   # the delay
W(0x0227)                       # st AL,@(2,Y)  delay low
W(LD_AH_Y(3))                   # ld AH,@(3,Y)  the MessageId (the next stage)
