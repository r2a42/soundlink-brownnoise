W(LD_AL_Y(2)); W(0x0134); W(ST_AL_Y(2))  # id += 1   (add AL,#1)
W(*CMPI_AL(STAGE3 + 1)); BR(BNE, "ARM_LOOP")
W(*LDI_AL(STAGE1)); W(ST_AL_Y(3))        # message id = T1
W(*LDI_AL(PRESS_DELAY)); W(ST_AL_Y(4))   # delay
BR(BRA, "SENDLATER")
LBL("STOP")
W(0xF80F)                       # leavel -8

# ---- SENDLATER: MessageSendLater(cave task, slot 3, 0, slot 4 ms) -- probe195's REARM, id and delay from slots.
# message slot 0, delay HIGH slot 1, delay LOW slot 2 (message-task-abi.md 1).
LBL("SENDLATER")
