# trap tail's `bra @0xFFFD` (0xE1, a terminator). Called by an ordinary `bsr`; the result is in AL.
#   STUB_CE : FD0B 0100 CE18 002B FC19 FF2B FF0E FDE1    (8 words)  PartitionGetInfo, the CONTROL
#   STUB_D3 : FD0B 0100 D318 002B FC19 FF2B FF0E FDE1    (8 words)  PartitionGetRawSerialSource
