LBL("T2B_BIG")
W(*LDI_AL(ID_SZ_BIG)); W(0xF80F)
LBL("T2B_SMALL")
W(*LDI_AL(ID_SZ_SMALL)); W(0xF80F)
LBL("T2B_FALSE")
W(*LDI_AL(ID_SZ_FALSE)); W(0xF80F)

# ---------------------------------------------------------------------- T1: GATE + the CONTROL
# Returns the id to speak in AL. GATE (probe190's form): FALSE = no .kap loaded = the DSP is not up: 0x21.
# CONTROL (V05 D2): PartitionGetInfo(1, 2, TYPE) through the STOCK stub (saves TYPE, 3 on this unit, F120), then slot 5
# is preset to 0xFFFF and the same call goes through the SYNTHESISED stub for trap 0xCE. A stub that returned without running
# the trap leaves 0xFFFF (and AL = 1 from the argument load): that FAILS. 0x1F "muted" only if the stub returned TRUE and wrote
# the SAME TYPE the stock stub wrote. 0x20 = the stub answered differently / FALSE; 0x1C = the STOCK call itself was FALSE.
LBL("T1")
W(0xF80B)                       # enterl -8
BSR("GATE")
W(CMP0); BR(BNE, "T1_DSP")
W(*LDI_AL(ID_NODSP)); W(0xF80F)
LBL("T1_DSP")
getinfo_prep(2)                 # TYPE
BSR(GETINFO)                    # the STOCK stub
W(CMP0); BR(BNE, "T1_STOCKOK")
W(*LDI_AL(ID_CTL_STOCKFAIL)); W(0xF80F)
LBL("T1_STOCKOK")
W(LD_AL_Y(5)); W(ST_AL_Y(3))    # slot 3 = the stock TYPE (low half)
W(0xFF14); W(ST_AL_Y(5))        # slot 5 = 0xFFFF, a sentinel the real trap must overwrite
getinfo_prep(2)
BSR("STUB_CE")                  # the SYNTHESISED stub, same arguments
W(CMP0); BR(BEQ, "T1_BAD")      # FALSE
W(LD_AL_Y(5)); W(0x0387)        # ld AL,@(5,Y) ; cmp AL,@(3,Y)
BR(BNE, "T1_BAD")
W(*LDI_AL(ID_CTL_OK)); W(0xF80F)
LBL("T1_BAD")
W(*LDI_AL(ID_CTL_BAD)); W(0xF80F)

LBL("T2A")
W(0xF80B)                       # enterl -8
getinfo_prep(2)                 # TYPE
BSR(GETINFO)
W(CMP0); BR(BEQ, "T2A_FALSE")
W(LD_AL_Y(5)); W(*CMPI_AL(3)); BR(BNE, "T2A_NOT3")
getinfo_prep(3)                 # STATE
BSR(GETINFO)
W(CMP0); BR(BEQ, "T2A_FALSE")
