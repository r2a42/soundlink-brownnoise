W(0xF80F)                       # leavel -8: the next tick is set

# ---- everything from here on is COLD code entered only by `bsr`. No explicit REGION() marker: the layout engine
# fills the const window first and spills into the dead-code region (probe193's approved placement) only when the
# window is full, so the number of region words is whatever does not fit (printed at the end).

# probe140's proven call shape: @(0,Y) = key, @(1,Y) = &slot4 (Bose's e415 idiom), AL = device 1, AH = partition 2;
# the 32-bit value lands in slots 4 (high) and 5 (low); the result in AL is the bool.
def getinfo_prep(key):
    W(*LDI_AL(key))             # ld AL,#key
    W(0x0027)                   # st AL,@(0,Y)
    W(0xE415)                   # ld AL,@0xffe4 (the Y mirror)
    W(0x0434)                   # add AL,#4
    W(0x0127)                   # st AL,@(1,Y)
    W(0x0114)                   # ld AL,#1   device = SERIAL_FLASH
    W(0x0210)                   # ld AH,#2   partition 2
# ---- GATE: KalimbaSendMessage(0x1072 SET_TONE_RATE, 8000, TONE_B, 0, 0) -> bool in AL, TRUE iff a .kap is loaded.
# This is probe190's proven form (0x1072 only, flashed 2026-10-13 17:23); probe191..195 added a DM shift poke
# (M[0x29e6] := 5) after it. R1 does NOT poke: it plays nothing, and a write into the DSP's memory has no business in a
# read-only census. Through KSEND's own frame (probe195 layout).
LBL("GATE")
W(*ca.imm_words(RATE, 0x10))    # ld AH,#8000
W(*ca.imm_words(0x1072, 0x14))  # ld AL,#0x1072   ...and fall into KSEND
LBL("KSEND")
W(0xF80B)                       # enterl -8
W(0x0327)                       # st AL,@(3,Y)  the message id
W(*ca.imm_words(TONE_B, 0x14))  # ld AL,#2
W(0x0027)                       # st AL,@(0,Y)  b = 2        slot 0
W(0x0014)                       # ld AL,#0
W(0x0127); W(0x0227)            # c = d = 0                  slots 1..2
W(0x0317)                       # ld AL,@(3,Y)
BSR(KALMSG)
W(0xF80F)                       # leavel -8, and AL carries the bool out

