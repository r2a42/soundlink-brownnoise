#!/usr/bin/env python3
"""verify_probe153: the refill loop with THE CLOSE DONE PROPERLY.

probe151 proved an explicit TransformStop+TransformDisconnect reclaims NOTHING
(~55 ticks, unchanged), so probe153 deletes them and goes after the thing
source.h has been complaining about all along: probe145 disconnected only the
SINK side before SourceClose, and "Source stream can be closed only if the
requested source stream is not connected to any stream."

THE FOUR ASSERTIONS THAT MATTER HERE, none of which an earlier harness made:

  * TransformFromSink, TransformStop and TransformDisconnect are NEVER called.
  * StreamDisconnect receives BOTH the source (AL = 0x58C0, cavesim's
    StreamRegionSource return) and the sink (AH = 0x55C0, its StreamKalimbaSink
    return). probe145 passed AL = 0, breaking only the sink side.
  * SourceClose receives that same source handle, and buf[1] carries it tick to
    tick.
  * when SourceClose returns FALSE the cave speaks 0x3A and the loop STOPS --
    no MessageSendLater, no re-arm. That bool is the whole point of the probe
    and five presses never read it.

Ids:

    SourceClose          == FALSE -> 0x3A "heart rate not detected"  (NEW)
    StreamRegionSource   == 0     -> 0x3B "adjust airbuds"
    TransformAdpcmDecode == 0     -> 0x3D "noise cancellation only"
    TransformStart       == FALSE -> 0x3D (merged)

1. The ARM (hook entry): trap order, then the 126 generated bytes compared
   BYTE-EXACT against the CONSULT8 Python reference, re-derived for SEED 0x7F,
   and the LFSR state written back to buf[0].
2. Three HANDLER ticks: the teardown sequence each time (TransformFromSink ->
   Stop -> Disconnect -> StreamDisconnect), the refill, the rebuild, the
   re-arm -- and the LFSR CONTINUING across fills.
3. Failure paths: every trap that can refuse, on both the arm and the tick
   path, checked for "no re-arm, no crash, leavel out" AND for the RIGHT
   SPOKEN ID:
       StreamRegionSource refused   -> 0x3B "adjust airbuds"
       TransformAdpcmDecode == 0    -> 0x3D "noise cancellation only"
       TransformStart == FALSE      -> 0x3D (merged)
   The ids are the whole point of the probe, so a wrong or missing one must
   fail this harness, not the press.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'xapvm'))
import cavesim                                                  # noqa: E402

SEED = 0x7F          # probe149: one-word seed (see the probe docstring)
NBYTES, NBLOCKS = 126, 40
BUF = cavesim.HEAP
CAVE = 0x3E21D


def reference_from(seed, blocks):
    """The CONSULT8 Python reference; returns (bytes, final_x)."""
    x = seed & 0xFFFF
    out = [0x0080, 0x00FF, 0x00FF, 0x00FF, 0x00FF, 0x00F7]
    for _ in range(blocks):
        x = (x >> 1) ^ ((0 - (x & 1)) & 0xB400)
        r = x & 0x88
        t = r >> 4
        out.append((0x30 ^ r) & 0xFF)
        out.append((0xCB ^ (r & 0x80) ^ t) & 0xFF)
        out.append((0x84 ^ ((r << 4) & 0xFFFF) ^ t) & 0xFF)
    return out, x


def buf_bytes(vm):
    return [vm.rd(BUF + 3 + i) & 0xFF for i in range(NBYTES)]


def trap_names(vm, stubs):
    return [stubs_inv.get(t, t) for t in vm.traps]


stubs_inv = {}


def run_arm(fail=()):
    vm, state, stubs, trapnums = cavesim.build(
        os.path.join(ROOT, 'build/hook/probe153_words.json'), fail=set(fail))
    stubs_inv.update({v: k for k, v in trapnums.items()})
    # cavesim has no DEFAULT_RETURNS entry for SourceClose, so an unset stub
    # would leave AL holding the source handle and read as TRUE by accident.
    # Make the healthy answer explicit; the FALSE case is driven below.
    vm.STUB_RET[trapnums['SourceClose']] = (0, 1 if 'SourceCloseFalse' not in fail
                                            else 0)
    vm.Y = cavesim.FRAME
    why, pc = vm.run(CAVE)
    return vm, why


def run_tick(vm, n=1):
    handler = 0x30000 | (json.load(
        open(os.path.join(ROOT, 'build/hook/probe153_words.json')))['0x3e21f'])
    for _ in range(n):
        vm.traps = []
        vm.AH = BUF                      # the MessageId IS buf
        vm.AL = 0xBA3C                   # Task (ignored)
        vm.Y = cavesim.FRAME
        why, pc = vm.run(handler)
        assert why == 'leavel', (why, pc)


def check_fill(vm, expect_bytes, expect_x, tag):
    got = buf_bytes(vm)
    assert got == expect_bytes, (
        '%s: generator bytes differ from the reference at %s' %
        (tag, [i for i in range(NBYTES) if got[i] != expect_bytes[i]][:4]))
    assert vm.rd(BUF) == expect_x, (
        '%s: buf[0] = %#06x, reference final x = %#06x' %
        (tag, vm.rd(BUF), expect_x))
    print('  %s: 126 bytes BYTE-EXACT vs reference; x -> %#06x' % (tag, expect_x))


def check_traps(vm, expected, tag):
    names = [stubs_inv.get(t, 'trap_%02x' % t) for t, _, _ in vm.traps]
    assert names == expected, '%s: traps %s != %s' % (tag, names, expected)
    print('  %s: traps %s' % (tag, ' '.join(expected)))


# probe149 keeps probe146's tick shape: NO per-tick SourceClose. SourceClose
# appears ONLY when ADPCM/TSTART fail on a fresh, never-pumped source. (That the
# per-tick close is absent is probe146's regime, which this probe deliberately
# does not change -- it only gives the failures a voice.)
TICK_TRAPS = ['StreamDisconnect', 'SourceClose', 'StreamRegionSource',
              'TransformAdpcmDecode', 'TransformStart', 'MessageSendLater']
SRC_H, KSINK_H = 0x58C0, 0x55C0   # cavesim's StreamRegionSource / KalimbaSink
GONE = ('TransformFromSink', 'TransformStop', 'TransformDisconnect')

print('1. ARM')
vm, why = run_arm()
assert why == 'leavel', why
names = [stubs_inv.get(t, 'trap_%02x' % t) for t, _, _ in vm.traps]
assert names == ['KalimbaSendMessage', 'malloc', 'StreamKalimbaSink',
                 'StreamRegionSource', 'TransformAdpcmDecode',
                 'TransformStart', 'MessageSendLater'], names
print('  traps: %s' % ' '.join(names))
ref, x = reference_from(SEED, NBLOCKS)
check_fill(vm, ref, x, 'fill#1')
assert not [1 for a, _ in vm.calls_seen if a == cavesim.SPEAK_ADDR], (
    'the healthy arm path must be SILENT')
print('  healthy arm path spoke nothing (correct)')
assert vm.rd(BUF + 1) == 0x58C0, (
    'arm must leave the SOURCE handle in buf[1], found %#06x' % vm.rd(BUF + 1))
print('  arm stored the source handle in buf[1] (%#06x)' % vm.rd(BUF + 1))

print('2. Three HANDLER ticks (the LFSR must CONTINUE across fills)')
for k in range(2, 5):
    vm.traps = []
    run_tick(vm, 1)
    check_traps(vm, TICK_TRAPS, 'tick#%d' % k)
    byname, bypair = {}, {}
    for t, ahal, _a2 in vm.traps:
        nm = stubs_inv.get(t, 'trap_%02x' % t)
        byname.setdefault(nm, []).append(ahal & 0xFFFF)
        bypair.setdefault(nm, []).append((ahal >> 16, ahal & 0xFFFF))
    for dead in GONE:
        assert dead not in byname, 'tick#%d: %s must NOT be called' % (k, dead)
    ah, al = bypair['StreamDisconnect'][0]
    assert (al, ah) == (SRC_H, KSINK_H), (
        'tick#%d: StreamDisconnect(AL=%#06x, AH=%#06x), expected the SOURCE '
        '%#06x and the SINK %#06x -- probe145 passed AL=0 and broke only the '
        'sink side' % (k, al, ah, SRC_H, KSINK_H))
    assert byname['SourceClose'] == [SRC_H], (
        'tick#%d: SourceClose got %s, expected the stored source %#06x'
        % (k, byname['SourceClose'], SRC_H))
    assert vm.rd(BUF + 1) == SRC_H, (
        'tick#%d: buf[1] = %#06x, expected the source %#06x'
        % (k, vm.rd(BUF + 1), SRC_H))
    print('  tick#%d: StreamDisconnect got BOTH sides; SourceClose got %#06x; '
          'buf[1] re-armed' % (k, SRC_H))
    ref, x = reference_from(x, NBLOCKS)
    check_fill(vm, ref, x, 'fill#%d' % k)
    pass  # probe149/146: no buf[1] tracking -- see the probe docstring

print('3. Failure paths')
for fail, n_traps, note in [
        ('KalimbaSendMessage', 1, 'gate bails: no DSP'),
        ('malloc', 2, 'pool exhausted'),
        ('StreamKalimbaSink', 3, 'no port-3 sink'),
        ('StreamRegionSource', 4, 'arm: rebuild fails, no timer (no close: '
                                 'the arm path never opened one)'),
        ('TransformAdpcmDecode', 6, 'arm: close the fresh source + no timer'),
        ('TransformStart', 7, 'arm: close the fresh source + no timer')]:
    vm, why = run_arm(fail=(fail,))
    names = [stubs_inv.get(t, 'trap_%02x' % t) for t, _, _ in vm.traps]
    assert why == 'leavel', (fail, why)
    assert len(names) == n_traps, (fail, names)
    assert 'MessageSendLater' not in names, (fail, names)
    assert ('SourceClose' in names) == (fail in ('TransformAdpcmDecode',
                                                 'TransformStart')), (fail, names)
    want = {'StreamRegionSource': 0x3B,
            'TransformAdpcmDecode': 0x3D, 'TransformStart': 0x3D}.get(fail)
    spoken = [v & 0xFFFF for a, v in vm.calls_seen if a == cavesim.SPEAK_ADDR]
    if want is None:
        assert not spoken, (fail, 'must stay SILENT, spoke %s' % spoken)
    else:
        assert spoken == [want], (
            fail, 'expected one id %#04x, got %s' % (want, spoken))
        print('    spoke %#04x -- the right id for %s' % (want, fail))
    print('  arm --fail %-22s -> %d traps (%s)' % (fail, n_traps, note))

for fail, rearms, note in [
        ('StreamRegionSource', False, 'tick: rebuild fails, loop STOPS'),
        ('TransformStart', False, 'tick: close the fresh source + loop STOPS')]:
    vm, why = run_arm()
    ref, x = reference_from(x, NBLOCKS)          # the arm's fill already ran
    import json as _json
    tn = _json.load(open(os.path.join(ROOT, 'tools/traps-bluelab73.json')))[fail]
    vm.STUB_RET[tn] = (0, 0)                     # fail only on the tick
    vm.traps = []
    run_tick(vm, 1)
    names = [stubs_inv.get(t, 'trap_%02x' % t) for t, _, _ in vm.traps]
    assert ('MessageSendLater' in names) == rearms, (fail, names)
    want = {'StreamRegionSource': 0x3B,
            'TransformAdpcmDecode': 0x3D, 'TransformStart': 0x3D}.get(fail)
    spoken = [v & 0xFFFF for a, v in vm.calls_seen if a == cavesim.SPEAK_ADDR]
    if want is None:
        assert not spoken, (fail, 'must stay SILENT, spoke %s' % spoken)
    else:
        assert spoken == [want], (
            fail, 'expected one id %#04x, got %s' % (want, spoken))
        print('    spoke %#04x from the message loop -- the right id' % want)
    print('  tick --fail %-22s -> %d traps (%s)' % (fail, len(names), note))

print('4. THE NEW CASE: SourceClose returns FALSE')
vm, why = run_arm()
import json as _json2
_tn = _json2.load(open(os.path.join(ROOT, 'tools/traps-bluelab73.json')))['SourceClose']
vm.STUB_RET[_tn] = (0, 0)                 # the close fails on the tick
vm.traps = []
run_tick(vm, 1)
_names = [stubs_inv.get(t, 'trap_%02x' % t) for t, _, _ in vm.traps]
_spoken = [v & 0xFFFF for a, v in vm.calls_seen if a == cavesim.SPEAK_ADDR]
assert _spoken == [0x3A], 'expected 0x3A on a FALSE close, spoke %s' % _spoken
assert 'MessageSendLater' not in _names, (
    'a FALSE close must STOP the loop, but it re-armed: %s' % _names)
assert 'StreamRegionSource' not in _names, (
    'a FALSE close must stop BEFORE rebuilding: %s' % _names)
print('  SourceClose FALSE -> spoke 0x3A, did NOT rebuild, did NOT re-arm')

print('\nALL SIM CHECKS PASS (probe153: both sides disconnected, SourceClose checked, 0x3A on FALSE; ids 0x3A / 0x3B / 0x3D verified)')
