#!/usr/bin/env python3
"""Rebuild the shipped 48 kHz brown-noise payload of the writer (probe393) and the loop (probe428) from source.

    python build/payload/build_payload.py            # regenerate (about 3-4 minutes), compare with the pinned hashes
    python build/payload/build_payload.py --check    # only check the shipped file's hash (instant)

Needs numpy and scipy. Nothing here touches a device.

The shipped file is build/payload/g10/brown_48000_58968_seamfix160_f480_b.adpcm (58,968 bytes of IMA ADPCM, one 2.457 s loop at 48 kHz).
It is synthetic noise (seeded Gaussian noise shaped to a brown spectrum with a bass bell and a mid dip); no recording is involved.
The chain, with a hash pinned after every step:

  1. build/payload/gen/hx-coverage/mk48_lf.py (seed 63; ROT=local DIP_DB=-10 DIP_HALF_MS=40)
        -> brown_48000_58968_lfd10L.adpcm   sha256 8cc5b91f...7960d   (seeded, fully deterministic: regenerated byte-identically)
  2. Tail: the last 47 bytes are replaced by TAIL below, so that the decoder ends in state (0, 0) and the file loops exactly.
        This tail was found by an offline dynamic-programming re-encode of the last 96 samples (the script that did it was not kept);
        the result is stored here as data and checked: the decoder must end in (0, 0), and only the last 41 bytes change.
        -> "g9"                             sha256 d233cbf0...8dd60a
  3. First nibble 7 -> 15 (byte 0x77 -> 0xF7: same step-index delta, only the sign, a constant -22 LSB offset). The product's
        first-bytes check uses these four bytes (f7 ff 72 6b).
  4. tools/seamfix.py (cut 160, fade 480): the last 480 samples fade to zero ahead of the speaker's early chunk cut.
        -> final                            sha256 6ea4564a...95c36
"""
import hashlib
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import adpcm  # noqa: E402
import seamfix  # noqa: E402

GEN = os.path.join(ROOT, "build", "payload", "gen", "hx-coverage")
LFD10L = os.path.join(ROOT, "build", "payload", "g8", "brown_48000_58968_lfd10L.adpcm")
FINAL = os.path.join(ROOT, "build", "payload", "g10", "brown_48000_58968_seamfix160_f480_b.adpcm")

SHA_LFD10L = "8cc5b91f01e2e396b462421d48d745b216d910b0a109f3ddbb9956a65e97960d"
SHA_G9 = "d233cbf0628c2f57bd43b175995c33a79a12319fbdf2bc3bce89d3e7288dd60a"
SHA_FINAL = "6ea4564a776320feb0146840db0a15dc1367f52e7cef52b0144e28e7e8f95c36"
TAIL_OFFSET = 58921
TAIL = bytes.fromhex(
    "2bbb039baab8080808080805a76739905a39a81441bb804ab883b83333333333333bbbbbbbbbbbbbbbbbbbbbbbbbbb")


def sha(b):
    return hashlib.sha256(b).hexdigest()


def need(ok, what):
    print(("ok    " if ok else "FAIL  ") + what)
    if not ok:
        sys.exit(1)


def main():
    if "--check" in sys.argv:
        need(os.path.exists(FINAL) and sha(open(FINAL, "rb").read()) == SHA_FINAL, "shipped payload matches the pinned sha256 " + SHA_FINAL[:8])
        return
    env = dict(os.environ, ROT="local", DIP_DB="-10", DIP_HALF_MS="40")
    print("step 1: generating (about 3-4 minutes) ...")
    subprocess.run([sys.executable, "-I", "mk48_lf.py", "48000"], cwd=GEN, env=env, check=True, stdout=subprocess.DEVNULL)
    lf = open(LFD10L, "rb").read()
    need(sha(lf) == SHA_LFD10L, "step 1 output matches sha256 " + SHA_LFD10L[:8])
    g9 = lf[:TAIL_OFFSET] + TAIL
    need(len(g9) == len(lf) == 58968, "step 2: tail replaced, length unchanged")
    need(sum(1 for a, b in zip(lf, g9) if a != b) == 41 and lf[:TAIL_OFFSET] == g9[:TAIL_OFFSET], "step 2: only the last 41 bytes differ")
    need(adpcm.decode_state(g9)[1] == (0, 0), "step 2: the decoder ends in state (0, 0)")
    need(sha(g9) == SHA_G9, "step 2 output matches sha256 " + SHA_G9[:8])
    f7 = bytes([g9[0] | 0x80]) + g9[1:]
    need(f7[:4].hex() == "f7ff726b", "step 3: first four bytes are f7 ff 72 6b")
    out = seamfix.seamfix(f7, 160, 480)[0]
    need(sha(out) == SHA_FINAL, "step 4 output matches sha256 " + SHA_FINAL[:8])
    if os.path.exists(FINAL):
        need(open(FINAL, "rb").read() == out, "identical to the shipped file")
    else:
        os.makedirs(os.path.dirname(FINAL), exist_ok=True)
        open(FINAL, "wb").write(out)
        print("wrote", FINAL)


main()
