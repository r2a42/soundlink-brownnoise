#!/usr/bin/env python3
"""fnprofile: characterise every function by the trap stubs it calls.

82.6% of the image's functions have no name (`docs/firmware-map.md`), and reading 4,691
of them by hand is not happening. But a function is largely characterised by the traps it
reaches: one that calls `StreamAudioSink` + `SinkConfigure` + `StreamConnect` is audio
setup whatever it is called, and one that calls `PsFullRetrieve` is reading config.

This computes, for every function, the set of trap stubs reachable from it directly, then
ranks the anonymous ones by caller count -- because a gate like the `cmp AL,#0x4003` at
`0x00ace` that silently invalidated five probes will be sitting in a high-traffic function
nobody has read.
"""
import collections
import json
import os
import sys

ROOT = __import__('os').path.dirname(__import__('os').path.dirname(__import__('os').path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'xapvm'))
import xapvm

BSR = 0x9C

w = xapvm.load_words(os.path.join(ROOT, 'firmware/bose/extracted/internal_fs/vm.app'))
hdr = w[:0x18]
ncode = (hdr[5] << 16) | hdr[6]
code = w[0x18:0x18 + ncode]
ins = list(xapvm.decode(code[:ncode]))

stubs, _ = xapvm.find_stubs(code)
trapnums = json.load(open(os.path.join(ROOT, 'tools/traps-bluelab73.json')))
num2name = {v: k for k, v in trapnums.items()}
stub_name = {}
for addr, num in (stubs.items() if isinstance(stubs, dict) else stubs):
    stub_name[addr] = num2name.get(num, 'trap_%#x' % num)

# function entries and the call graph
entries = set()
calls = collections.defaultdict(set)
callers = collections.defaultdict(set)
for a, op, v, ln in ins:
    if op == 0x0B:
        entries.add(a)
    elif op == BSR:
        entries.add((a + ln - 1 + v) & 0x3FFFF)
entries = sorted(entries)


def fn_of(a):
    lo, hi, best = 0, len(entries) - 1, None
    while lo <= hi:
        mid = (lo + hi) // 2
        if entries[mid] <= a:
            best = entries[mid]; lo = mid + 1
        else:
            hi = mid - 1
    return best


for a, op, v, ln in ins:
    if op != BSR:
        continue
    tgt = (a + ln - 1 + v) & 0x3FFFF
    f = fn_of(a)
    if f is not None:
        calls[f].add(tgt)
        callers[tgt].add(f)

named = set()
import re
for f in ('named-functions.txt', 'named-app-functions.txt'):
    path = os.path.join(ROOT, 'build/analysis', f)
    if not os.path.exists(path):
        continue
    for line in open(path, encoding='latin1'):
        m = re.search(r'0x([0-9a-fA-F]{3,6})', line)
        if m:
            named.add(int(m.group(1), 16))
named |= set(stub_name)

rows = []
for f in entries:
    if f in named:
        continue
    traps = sorted(stub_name[t] for t in calls.get(f, ()) if t in stub_name)
    rows.append((len(callers.get(f, ())), f, traps, len(calls.get(f, ()))))
rows.sort(reverse=True)

print('%d anonymous functions; %d of them call at least one named trap\n'
      % (len(rows), sum(1 for r in rows if r[2])))
print('Top anonymous functions by caller count:')
print('%-10s %7s %6s  %s' % ('function', 'callers', 'callees', 'traps it reaches directly'))
for ncall, f, traps, nc in rows[:28]:
    t = ', '.join(traps[:6]) + (' …' if len(traps) > 6 else '')
    print('fn_%05x %7d %6d  %s' % (f, ncall, nc, t if t else '-'))

# Which anonymous functions touch the audio/stream plane at all?
AUDIO = ('Stream', 'Sink', 'Source', 'Transform', 'Kalimba', 'Audio', 'Codec', 'Partition')
aud = [(n, f, ts) for n, f, ts, _ in rows
       if any(t.startswith(AUDIO) for t in ts)]
print('\n%d anonymous functions touch the audio/stream/partition traps.' % len(aud))
print('The ten with the most callers:')
for n, f, ts in aud[:10]:
    print('  fn_%05x  %3d callers  %s' % (f, n, ', '.join(t for t in ts if t.startswith(AUDIO))[:88]))

out = os.path.join(ROOT, 'build/analysis/fn-profiles.txt')
with open(out, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('# Every function and the trap stubs it calls directly.\n'
             '# "anon" marks a function with no name from library matching or the stub table.\n'
             '# Generated by the profiler in the session scratchpad; see docs/firmware-map.md.\n\n')
    for f in entries:
        traps = sorted(stub_name[t] for t in calls.get(f, ()) if t in stub_name)
        tag = '' if f in named else ' anon'
        fh.write('fn_%05x%s  callers=%d  traps=%s\n'
                 % (f, tag, len(callers.get(f, ())), ','.join(traps) if traps else '-'))
print('\nfull profile -> build/analysis/fn-profiles.txt')
