#!/usr/bin/env python3
"""Regenerate tools/bose-stubs.json and docs/trap-stub-table.md.

Finds every trap stub in the speaker's vm.app by its fixed shape --
`enterl -3 ; ld X,#<trap> ; bra <dispatcher>` -- and names it from the
trap table of the matching BlueLab version.

**Trap numbers are NOT stable between BlueLab versions.** 173 of the 257
names shared by BlueLab 7.3.1 and 7.4 have different numbers. The speaker's
vm.app stamps VM version 0x3200, so it is a BlueLab 7.3.x image and must be
read with tools/traps-bluelab73.json. See docs/trap-numbering.md for the
evidence; using the 7.4 table here is what made probes 46, 47 and 52-56
call the wrong traps.

    python tools/gen-stub-table.py
"""
import json
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, 'firmware/bose/extracted/internal_fs/vm.app')
HDR = 24                      # words of vm.app header; `a` = index - HDR
TRAPS = 'tools/traps-bluelab73.json'   # the speaker is a BlueLab 7.3.x image


def sext8(b):
    return b - 256 if b & 0x80 else b


def fold(prefixes, final):
    v = 0
    for a in prefixes:
        v = (v + sext8(a)) << 8
    return v + sext8(final)


def words(path):
    d = open(path, 'rb').read()
    return [struct.unpack_from('<H', d, i)[0] for i in range(0, len(d) & ~1, 2)]


def find_stubs(w):
    stubs, i = {}, 0
    while i < len(w) - 6:
        if w[i] == 0xFD0B:                       # enterl -3
            j, pfx = i + 1, []
            while j < len(w) and (w[j] & 0xFF) == 0x00 and w[j] and len(pfx) < 3:
                pfx.append(w[j] >> 8); j += 1
            if j < len(w) and (w[j] & 0xFF) == 0x18:       # ld X,#trap
                t, k = fold(pfx, w[j] >> 8), j + 1
                if k < len(w) and w[k] == 0x0000:
                    k += 1
                p2 = []
                while k < len(w) and (w[k] & 0xFF) == 0x00 and w[k] and len(p2) < 3:
                    p2.append(w[k] >> 8); k += 1
                if k < len(w) and (w[k] & 0xFF) == 0xE0 and 0 <= t < 0x200:
                    stubs.setdefault(t, i - HDR)              # bra dispatcher
        i += 1
    return stubs


HEADER = """# Bose `vm.app`: the complete trap stub table

All 151 trap stubs in the speaker's `vm.app`, found by the shape
`enterl -3 ; ld X,#<trap> ; bra <dispatcher>`.

**Names come from BlueLab 7.3.1's `vmbuilder.exe`, not 7.4's.** The
speaker's app stamps VM version 0x3200; 7.3.1 stamps 0x3209 and 7.4 stamps
0x3500, and 173 of the 257 shared trap names are numbered differently
between the two. `docs/trap-numbering.md` has the evidence and the list of
probes this invalidates.

Addresses are in the project's `a` space -- code-relative word addresses,
i.e. **file word index minus the 24-word header**. Check:
`file_offset = 0x12E97C + 2a`.

Generated by `tools/gen-stub-table.py`.

| trap | name | stub `a` |
|---|---|---|
"""


def main():
    w = words(APP)
    names = {v: k for k, v in
             json.load(open(os.path.join(ROOT, TRAPS))).items()}
    rows = sorted(find_stubs(w).items())
    json.dump({names.get(t, 'trap_%02x' % t): a for t, a in rows},
              open(os.path.join(ROOT, 'tools/bose-stubs.json'), 'w'),
              indent=1, sort_keys=True)
    with open(os.path.join(ROOT, 'docs/trap-stub-table.md'), 'w') as f:
        f.write(HEADER)
        for t, a in rows:
            f.write('| 0x%02X | `%s` | **0x%03X** |' % (t, names.get(t, '?'), a) + chr(10))
    print('%d stubs' % len(rows))


if __name__ == '__main__':
    main()
